const root = path.resolve(import.meta.dirname, '../client/lib/l10n');
for (const file of fs.readdirSync(root).filter(name => /^app_.+\.arb$/.test(name))) {
  const filename = path.join(root, file);
  const existing = JSON.parse(fs.readFileSync(filename, 'utf8'));
  const messages = file === 'app_zh.arb' ? zh : file === 'app_zh_TW.arb' ? traditional : en;
  for (const [key, value] of Object.entries(messages)) existing[key] ??= value;
  fs.writeFileSync(filename, JSON.stringify(existing, null, 2) + '\n');
}
